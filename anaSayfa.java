    private void barkodNo_alaniKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_barkodNo_alaniKeyPressed

        if (evt.getKeyCode() == KeyEvent.VK_ENTER) {
            // Enter tuşuna basıldığında barkod numarasını alması için yazdım.
            String barkod = barkodNo_alani.getText();
            try {
                connection = dbHelper.getConnection();// Veritabanı bağlantısını almalı.
                // Bağlantı alınamazsa
                if (connection == null) {
                    // Kullanıcıya hata mesajı gösterir.
                    JOptionPane.showMessageDialog(this, "Veritabanı bağlantısı kurulamadı.");
                    return; // Metodu sonlandır
                }
                // Veritabanından ürünü barkod numarasına göre sorguladım.
                statement = connection.prepareStatement("SELECT * FROM kırtasiye.ürünler WHERE barkod_no = ?");
                statement.setString(1, barkod);
                resultSet = statement.executeQuery();

                // Ürün bulunamazsa
                if (!resultSet.next()) {
                    // Kullanıcıya hata mesajı gösterir.
                    JOptionPane.showMessageDialog(this, "Ürün kodu bulunamadı.");
                } else {
                    // Ürün bulunursa ürün adı ve fiyatını ilgili alanlara yazması için kullandım.
                    String urun_adı = resultSet.getString("ürün_adi");
                    String fiyat = resultSet.getString("fiyat");
                    ürünadi_alani.setText(urun_adı.trim());
                    fiyat_alani.setText(fiyat.trim());
                }
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, "Veritabanı sorgulanırken bir hata oluştu.");
            }
        }
    }//GEN-LAST:event_barkodNo_alaniKeyPressed

