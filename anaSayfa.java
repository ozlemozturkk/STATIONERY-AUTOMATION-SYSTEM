    private void silinecek() {
        int sum = 0;

        // Tablodaki tüm satırların toplamını hesaplasını için yazdım.
        for (int i = 0; i < satisTable.getRowCount(); i++) {
            sum += Integer.parseInt(satisTable.getValueAt(i, 4).toString());
        }

        int selectedRow = satisTable.getSelectedRow();

        // Eğer hiçbir satır seçilmediyse (-1 döner) .
        if (selectedRow != -1) {
            // Silinecek olan satırın toplam değerini alması için yazdım.
            int silinecekToplam = Integer.parseInt(satisTable.getValueAt(selectedRow, 4).toString());

            // Tablodan seçili satırı kaldırılması için yazdım.
            DefaultTableModel model = (DefaultTableModel) satisTable.getModel();
            model.removeRow(selectedRow);

            // Güncellenmiş toplam değeri hesapladım ve toplam_alani'ni güncelledim
            int yeniToplam = sum - silinecekToplam;
            toplam_alani.setText(Integer.toString(yeniToplam));
        }
    }

    private int stokSorgu(String barkodNo) throws SQLException {
        barkodNo = barkodNo_alani.getText();

        // Veritabanından stok adedini sorgulamak için SQL sorgusu hazırladım.
        String stokSorgu = "SELECT stok_adedi FROM kırtasiye.ürünler WHERE barkod_no = ?";
        try (Connection connection = dbHelper.getConnection(); PreparedStatement stokSorguStatement = connection.prepareStatement(stokSorgu)) {
            // SQL sorgusunda parametre olarak barkod numarasını kullanmasını sağladım.
            stokSorguStatement.setString(1, barkodNo);
            //Sorguyu çalıştırır ve sonucu almayı sağlar.
            ResultSet resultSet = stokSorguStatement.executeQuery();

            // Sonuç kümesinde bir sonraki satır varsa, yani barkod numarasına sahip bir ürün bulunmuşsa,
            if (resultSet.next()) {
                return resultSet.getInt("stok_adedi");
            } else {
                //ürün bulunamazsa -1 değeri döndürür.
                return -1;
            }
        }
    }
    private void ekleButonuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ekleButonuActionPerformed
        // Kullanıcıdan girdileri aldım: barkod numarası, ürün adı, fiyat ve adet.
        barkodNo = barkodNo_alani.getText();
        ürün_adi = ürünadi_alani.getText();
        fiyat = fiyat_alani.getText();
        adet = adet_alani.getText();

        //Diğer alanlar barkod numarasını girdiğimizde direkt geliyor ama adet kısmına biz yazacağımız için boş bırakılmaması gerekiyor.Bunun içinde adet alanın boş olup olmadığını kontrol ettim.
        if (adet.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Lütfen adeti giriniz. Adet alanı boş bırakılamaz!");
            return;
        }
        // Satırların toplamını hesaplamak için bir değişken tanımladım.
        int sum = 0;

        // Tablodaki tüm satırların toplamını hesaplamasını sağladım.
        for (int i = 0; i < satisTable.getRowCount(); i++) {
            sum += Integer.parseInt(satisTable.getValueAt(i, 4).toString());
        }

        // Girişten alınan fiyat ve adet bilgileri integera dönüştürerek ayrı değişkenlere atanır.
        int fiyatt = Integer.parseInt(fiyat);
        int adett = Integer.parseInt(adet);

        // Yeni toplam hesaplanır ve mevcut toplama eklenmesini sağladım.
        int yeniToplam = fiyatt * adett;
        sum += yeniToplam;

        // Toplam alanına yeni toplam değeri yazılır.
        toplam_alani.setText(Integer.toString(sum));

        try {

            // Stok adedini kontrol etmesini sağladım.
            int stokAdedi = stokSorgu(barkodNo);

            if (stokAdedi == -1) {
                // Ürün bulunamadı, uyarı verir.
                JOptionPane.showMessageDialog(null, "Ürün bulunamadı!");
                return; // İşlemi durdurur.
            }

            if (adett > stokAdedi) {
                // Eğer stok yetersizse , uyarı verir.
                JOptionPane.showMessageDialog(null, "Yetersiz stok! Mevcut stok: " + stokAdedi);
                return; // İşlemi durdurur.
            }

            int yeniStokAdedi = stokAdedi - adett; // Yeni stok adedi hesaplar.
            connection = dbHelper.getConnection();// Veritabanı bağlantısını aldım.

            // Veritabanına satış bilgilerini eklemek için SQL sorgusunu hazırlamasını ve çalıştırmasını sağladım.
            statement = connection.prepareStatement("INSERT INTO kırtasiye.satis(barkod, ürün_adi, fiyat, adet ,toplam) VALUES ( ?, ?, ?, ? ,?)");

            statement.setString(1, barkodNo);
            statement.setString(2, ürün_adi);
            statement.setString(3, fiyat);
            statement.setString(4, adet);
            statement.setInt(5, yeniToplam);
            statement.executeUpdate();

            // Stok adedini güncellemek için sql ifadesi yazdım.
            String stokGuncelle = "UPDATE kırtasiye.ürünler SET stok_adedi = ? WHERE barkod_no = ?";
            PreparedStatement stokGuncelleStatement = connection.prepareStatement(stokGuncelle);
            stokGuncelleStatement.setInt(1, yeniStokAdedi);
            stokGuncelleStatement.setString(2, barkodNo);
            stokGuncelleStatement.executeUpdate();

            // Metin alanlarını temizlesini sağladım.
            barkodNo_alani.setText("");
            ürünadi_alani.setText("");
            fiyat_alani.setText("");
            adet_alani.setText("");

        } catch (SQLException ex) {
            // Herhangi bir SQL hatası durumunda hata mesajını gösterir.
            dbHelper.ShowError(ex);
        }

        // Satış tablosuna yeni bir satır eklemek için veri modelini güncellemesi için oluşturdum.
        DefaultTableModel model = (DefaultTableModel) satisTable.getModel();
        Object[] rowData = {barkodNo, ürün_adi, fiyat, adet, yeniToplam};
        model.addRow(rowData);


    }//GEN-LAST:event_ekleButonuActionPerformed

