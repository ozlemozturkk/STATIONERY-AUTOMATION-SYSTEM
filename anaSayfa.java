    private void müsteridiKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_müsteridiKeyPressed

// Enter tuşuna basıldığında müşteri kimlik numarasını alır.
        if (evt.getKeyCode() == KeyEvent.VK_ENTER) {
            String id = müsteridi.getText();
            try {
                connection = dbHelper.getConnection();
                // Bağlantı alınamazsa
                if (connection == null) {
                    // Kullanıcıya hata mesajı gösterir.
                    JOptionPane.showMessageDialog(this, "Veritabanı bağlantısı kurulamadı.");
                    return; // Metodu sonlandır
                }
                // Veritabanından müşteriyi sorgular.
                statement = connection.prepareStatement("SELECT * FROM kırtasiye.müsteri WHERE id = ?");
                statement.setString(1, id);
                resultSet = statement.executeQuery();

                // Müşteri bulunamazsa
                if (!resultSet.next()) {
                    // Kullanıcıya hata mesajı gösterir.
                    JOptionPane.showMessageDialog(this, "Müşteri kodu bulunamadı.");
                } else {
                    // Müşteri bulunursa ad ve soyadını ilgili alana yazması için kullandım.
                    String ad = resultSet.getString("ad");
                    String soyad = resultSet.getString("soyad");
                    musteriAdiAlani.setText(ad + " " + soyad);// ad ve soyad ikisinin de gözükmesi için bu şekilde yazdım.
                }
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, "Veritabanı sorgulanırken bir hata oluştu.");
            }
        }


    }//GEN-LAST:event_müsteridiKeyPressed

