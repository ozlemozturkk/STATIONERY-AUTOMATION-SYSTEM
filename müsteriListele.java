    private void silButonuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_silButonuActionPerformed
        if (add_alani.getText().trim().isEmpty() || soyad_alani.getText().trim().isEmpty() || telefonNo_alani.getText().trim().isEmpty() || mail_alani.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Lütfen Tablodan Listeleme Yapıp Belirli Bir Satır Seçip Öyle Silme İşlemi Yapın");
        } else {
            try {
                connection = dbHelper.getConnection();

                // Tablo modelinden seçilen satırın indeksini ve müşteri ID'sini almak için oluşturdum.
                DefaultTableModel model = (DefaultTableModel) müsteriTable.getModel();
                int selectedIndex = müsteriTable.getSelectedRow();
                int id = Integer.parseInt(model.getValueAt(selectedIndex, 0).toString());

                // Veritabanından müşteriyi silmek için SQL sorgusu oluşturdum.
                statement = connection.prepareStatement("DELETE FROM kırtasiye.müsteri WHERE id=?");
                statement.setInt(1, id);
                // SQL sorgusunu veritabanına göndermek için kullandım.
                statement.executeUpdate();
                JOptionPane.showMessageDialog(this, add_alani.getText() + " İsimli Müşteri Silindi.");

                // Tablodan seçilen satırı ve ilgili verileri kaldırmak için kullandım.
                model.removeRow(selectedIndex);

                add_alani.setText("");
                soyad_alani.setText("");
                telefonNo_alani.setText("");
                mail_alani.setText("");

            } catch (SQLException ex) {
                dbHelper.ShowError(ex);
            }
        }
    }//GEN-LAST:event_silButonuActionPerformed

