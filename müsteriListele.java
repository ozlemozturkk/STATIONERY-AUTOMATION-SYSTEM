    private void müsteriListeleme() throws SQLException {

        connection = dbHelper.getConnection();
        //Müşteri tablosundaki verileri tutmak için oluşturduğum model :
        DefaultTableModel model = (DefaultTableModel) müsteriTable.getModel();
        model.setRowCount(0); //Tekrarlanan verilerin önüne geçilmesini sağlamak için kullandım.

        try {
            //tüm müşterileri yazdırmak için sql ifadesini böyle kullandım.
            statement = connection.prepareStatement("SELECT * FROM kırtasiye.müsteri");
            resultSet = statement.executeQuery();

            while (resultSet.next()) {

                Object[] row = new Object[müsteriTable.getColumnCount()]; // müşteri tablosundaki sütun sayısı kadar yeni bir Object dizisi oluşturdum.
                // resultSetten gelen verileri alır ve bunları satırlara  eklemesi için :
                row[0] = resultSet.getString("id"); // sonuç kümesindeki id  sütun verileri alınıp satır  dizisine eklemesini sağladım.
                row[1] = resultSet.getString("ad");
                row[2] = resultSet.getString("soyad");
                row[3] = resultSet.getString("telefon_no");
                row[4] = resultSet.getString("mail");
                model.addRow(row);// oluşan satırı modele eklemek için kullandım
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }

