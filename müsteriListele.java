private void guncelle() {
        try {
            connection = dbHelper.getConnection();
            // Tablo modelinden seçilen satırın indeksini almak için kullandım.
            DefaultTableModel model = (DefaultTableModel) müsteriTable.getModel();
            int selectedIndex = müsteriTable.getSelectedRow();

            // seçilen lomüşterinin idsini aldım.
            int id = Integer.parseInt(model.getValueAt(selectedIndex, 0).toString());

            // yeni müşteri bilgileri almak için ekledim.
            String yeniAd, yeniSoyad, yeniTelefon, yeniMail;
            yeniAd = add_alani.getText();
            yeniSoyad = soyad_alani.getText();
            yeniTelefon = telefonNo_alani.getText();
            yeniMail = mail_alani.getText();

            //güncelleme için sql ifadesi oluşturdum.
            statement = connection.prepareStatement("update kırtasiye.müsteri set ad=?,soyad=?,telefon_no=?,mail=? where id=?");

            // sql ifadesindeki soru işaretinin (?) yerlerini doldurmak için oluşturdum.
            statement.setString(1, yeniAd);
            statement.setString(2, yeniSoyad);
            statement.setString(3, yeniTelefon);
            statement.setString(4, yeniMail);
            statement.setInt(5, id);
            //güncelleme sorgusunu veri tabanına göndermek için kullandım.
            statement.executeUpdate();

            // Güncellenmiş veriyi tabloya yansıtmak için ilgili satırı doğrudan güncelleyebilmek için kullandığım yöntem :
            model.setValueAt(yeniAd, selectedIndex, 1);
            model.setValueAt(yeniSoyad, selectedIndex, 2);
            model.setValueAt(yeniTelefon, selectedIndex, 3);
            model.setValueAt(yeniMail, selectedIndex, 4);
            JOptionPane.showMessageDialog(this, " Müşteri Güncellendi.");

            add_alani.setText("");
            soyad_alani.setText("");
            telefonNo_alani.setText("");
            mail_alani.setText("");

        } catch (SQLException ex) {
            dbHelper.ShowError(ex);
        }
    }
    private void güncelleButonuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_güncelleButonuActionPerformed
        //Boş alan kontrolü oluşturdum.
        if (add_alani.getText().trim().isEmpty() || soyad_alani.getText().trim().isEmpty() || telefonNo_alani.getText().trim().isEmpty() || mail_alani.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Lütfen Boş Alanları Doldurunuz!");

            // Alanlar doluysa, girilen verilerin doğruluğunu kontrol etmeli.
        } else {

            // Ad için doğrulama: İki veya tek isim olabilir .Sadece harflerden oluşmalı, Türkçe karakter içermemeli
            Pattern pAd = Pattern.compile("^[a-zA-Z]+(\\s[a-zA-Z]+)?$");
            Matcher mAd = pAd.matcher(add_alani.getText());

            // Soyad için doğrulama: İki veya tek soyad olabilir .Sadece harflerden oluşmalı, Türkçe karakter içermemeli
            Pattern pSoyad = Pattern.compile("^[a-zA-Z]+(\\s[a-zA-Z]+)?$");
            Matcher mSoyad = pSoyad.matcher(soyad_alani.getText());

            // Email için doğrulama
            Pattern pMail = Pattern.compile("\\w+@\\w+\\.\\w+");
            Matcher mMail = pMail.matcher(mail_alani.getText());

            // Telefon numarası için doğrulama (05*********)
            Pattern pTelefonNo = Pattern.compile("0[0-9]{10}");
            Matcher mTelefonNo = pTelefonNo.matcher(telefonNo_alani.getText());

            if (!mTelefonNo.matches()) {
                // Telefon numarası geçerli değilse, kullanıcıya uyarı vermeli
                JOptionPane.showMessageDialog(this, "Hatalı telefon numarası girdiniz.(05*********)");
                // Soyad geçerli değilse, kullanıcıya uyarı vermeli
            } else if (!mSoyad.matches()) {
                JOptionPane.showMessageDialog(this, "Geçersiz soyad giriniz . Soyad sadece harflerden oluşmaktadır . Türkçe karakter kullanmayınız.");
                // Ad geçerli değilse, kullanıcıya uyarı vermeli
            } else if (!mAd.matches()) {
                JOptionPane.showMessageDialog(this, "Geçersiz ad giriniz . Ad sadece harflerden oluşmaktadır . Türkçe karakter kullanmayınız.");
                // Email geçerli değilse, kullanıcıya uyarı vermeli
            } else if (!mMail.matches()) {
                JOptionPane.showMessageDialog(this, "Hatalı email adresi girdiniz.( email@gmail.com");
            } else {
                // Tüm girdiler geçerli ise, güncelleme işlemini gerçekleştirmeli.
                guncelle();
            }

        }


    }//GEN-LAST:event_güncelleButonuActionPerformed

