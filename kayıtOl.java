    public void ekle() throws SQLException {

        try {

            connect = db.getConnection();

            //Aynı kullanıcıya hata vermesi için : 
            // Veritabanından "kırtasiye" şemasındaki "giris" tablosundan belirli bir kullanıcı adına göre veri seçer.
            // "?" yerine kullanıcı tarafından girilen kullanıcı adını parametre olarak kullanır.                
            statement = connect.prepareStatement("select * from kırtasiye.giris where Kullanici_adi=?");
            // Kullanıcı tarafından girilen kullanıcı adını SQL sorgusuna parametre olarak ekler.
            statement.setString(1, KullaniciAdiAlani.getText());
            // Sorguyu çalıştır ve sonuçları resultSet değişkenine atar.
            resultSet = statement.executeQuery();

            //Daha okunacak veri var mı ? 
            if (resultSet.next()) {
                JOptionPane.showMessageDialog(null, "Girdiğiniz Kullanıcı Adı Kayıtlı! Lütfen Farklı Bir Kullanıcı Adı Giriniz.");

            } else {

                // Yeni kullanıcı veritabanına ekleme işlemi gerçekleştirilir.
                String sql = "insert into kırtasiye.giris(AdSoyad,Email,Kullanici_adi,Sifre) values(?,?,?,?)";
                statement = connect.prepareStatement(sql);

                // İlk yer tutucusu (1. sıradaki '?') 'AdSoyad' değişkeniyle doldurmasını sağladım.
                statement.setString(1, user.getAdvesoyad());

                // İlk yer tutucusu (1. sıradaki '?') 'Email' değişkeniyle doldurmasını sağladım.
                statement.setString(2, user.getEmail());

                // İlk yer tutucusu (1. sıradaki '?') 'Kullanici_adi' değişkeniyle doldurmasını sağladım.
                statement.setString(3, user.getKullanici_adi());

                // İlk yer tutucusu (1. sıradaki '?') 'Sifre' değişkeniyle doldurmasını sağladım.
                statement.setString(4, user.getParola());
                statement.executeUpdate();// sql komutu veritabanında çalıştırılır.
                JOptionPane.showMessageDialog(null, "KAYIT BAŞARIYLA EKLENDİ.");
            }
        } catch (SQLException ex) {
            db.ShowError(ex);
        }

    }

