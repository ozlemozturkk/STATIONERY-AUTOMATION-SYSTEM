    private void kayıt_butonuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_kayıt_butonuActionPerformed
        if (KullaniciAdiAlani.getText().trim().isEmpty() || sifre_alani.getText().trim().isEmpty() || email_alani.getText().trim().isEmpty() || adSoyadAlani.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Lütfen Boş Alanları Doldurunuz!");
        } else {
            // Ad ve soyadın doğruluğunu kontrol etmek için :
            Pattern pAdVeSoyad = Pattern.compile("[a-zA-Z]+\\s+[a-zA-Z]+");
            // Oluşturulan desen, adSoyadAlani'ndaki metinle eşleştirilmesi için kullandım.
            Matcher mAdVeSoyad = pAdVeSoyad.matcher(adSoyadAlani.getText());

            // Kullanıcı adının doğruluğunu kontrol etmek için :Sadece küçük harf (a-z), büyük harf (A-Z), rakam (0-9) veya alt çizgi (_) karakterlerinden oluşmalıdır.
            Pattern pKullaniciAdi = Pattern.compile("[a-zA-Z0-9_]+");
            Matcher mKullaniciAdi = pKullaniciAdi.matcher(KullaniciAdiAlani.getText());

            // Email adresinin doğruluğunu kontrol etmek için :
            Pattern pMail = Pattern.compile("\\w+@\\w+\\.\\w+");
            Matcher mMail = pMail.matcher(email_alani.getText());

            // Şifre doğruluğunu kontrol etmek için :
            Pattern pSifre = Pattern.compile("[0-9]+");
            Matcher mSifre = pSifre.matcher(sifre_alani.getText());

            //radiobutonunun ikisi de seilmezse verilcek hata :
            if (!kadınButton.isSelected() && !erkekButton.isSelected()) {
                cinsiyetLabel.setText("Lütfen cinsiyetinizi seçiniz!");
                // Eğer şifre metni desenle eşleşmiyorsa:
            } else if (!mSifre.matches()) {
                // Şifre etiketine uygun bir hata mesajı atanıyor.
                sifreLabel.setText("Şifreniz sadece rakamlardan oluşmalıdır.");
            } else if (!mAdVeSoyad.matches()) {
                advesoyadLabel.setText("Geçersiz ad ve soyad girdiniz.Türkçe karakter kullanmayınız...");
            } else if (!mKullaniciAdi.matches()) {
                sifreLabel.setText("Kullanıcı adınız sadece harflerden  , rakamlardan veya alt çizgiden oluşmalıdır.(kullanici123,Kullanici_Adi)");
            } else if (!mMail.matches()) {
                emailLabel.setText("Hatalı email adresi girdiniz.Örnek : email@gmail.com");
                // Diğer durumlarda (tüm girişler geçerliyse):
            } else {
                // Tüm bilgiler doğruysa, önceki uyarıları temizler.           
                advesoyadLabel.setText(null);
                kullaniciAdiLabel.setText(null);
                emailLabel.setText(null);
                sifreLabel.setText(null);
                try {
                    // Kullanıcı nesnesi oluşturdum ve veritabanına ekledim.
                    user = new User(adSoyadAlani.getText(), email_alani.getText(), KullaniciAdiAlani.getText(), new String(sifre_alani.getPassword()));
                    ekle();// Kullanıcı veritabanına eklenmesini sağladım.
                    //Giriş ekranını açar .
                    kırtasiye_giris giris = new kırtasiye_giris();
                    giris.setVisible(true);
                } catch (SQLException ex) {
                    db.ShowError(ex);

                }
            }
        }

    }//GEN-LAST:event_kayıt_butonuActionPerformed

